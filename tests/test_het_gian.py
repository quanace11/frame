import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); DIST = os.environ.get('FS_DIST') or os.path.join(ROOT, 'dist'); ASSETS = os.path.join(HERE, 'assets'); OUT = os.path.join(HERE, 'out')
os.makedirs(OUT, exist_ok=True); os.chdir(OUT)   # screenshots/outputs go to tests/out
CHROME = os.environ.get('CHROME', '/usr/bin/google-chrome')
import asyncio, subprocess, time
from playwright.async_api import async_playwright
srv = subprocess.Popen(['python3','-m','http.server','8883'], cwd=DIST, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
import atexit; atexit.register(srv.kill)   # never leave the server behind when the test crashes (a later run would test a stale build)
time.sleep(1)
# Gestures 😡 Ngửa mặt hét giận / 🤬 Giơ nắm đấm gào: head squashed toward the neck (thrown back, works from behind too),
# shoulders up, body trembles with feet planted, camera shake + "roar" SFX, all ONE undo step.
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=CHROME, args=['--no-sandbox'])
        pg = await b.new_page(viewport={'width':1280,'height':900}); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.add_init_script("new MutationObserver(()=>document.querySelectorAll('.tabhide').forEach(e=>e.classList.remove('tabhide'))).observe(document,{subtree:true,attributes:true,childList:true,attributeFilter:['class']})")
        await pg.goto('http://localhost:8883/index.html'); await pg.wait_for_timeout(800); await pg.click('text=Bắt đầu vẽ')
        await pg.set_input_files('#imgFile', os.path.join(ASSETS, 'drawn_char.png')); await pg.wait_for_timeout(400)
        await pg.click('[data-mode=pp]'); await pg.wait_for_timeout(300)
        await pg.wait_for_function("document.querySelector('#impBusy').hidden", timeout=180000); await pg.wait_for_timeout(500)
        await pg.click('.dlg .btns >> text=Dùng'); await pg.wait_for_timeout(600)
        await pg.click('#ppCutAuto'); await pg.click('#ppLabCut'); await pg.wait_for_function('S.pp && S.pp.parts.length', timeout=180000); await pg.wait_for_timeout(300)
        await pg.evaluate("openTab('pp','frames')"); await pg.wait_for_timeout(200)
        names = await pg.evaluate("[...document.querySelectorAll('#ppGests button')].map(b=>b.textContent)")
        print('buttons', '😡 Ngửa mặt hét giận' in names and '🤬 Giơ nắm đấm gào' in names)
        ids = await pg.evaluate("Object.fromEntries(S.pp.parts.filter(p=>p.role).map(p=>[p.role,p.id]))")
        a0 = await pg.evaluate("ppCurAbs(S.frames[0], ppSelChar())")
        u0 = await pg.evaluate("undoStack.length")
        await pg.click('#ppGests >> text=Ngửa mặt hét giận'); await pg.wait_for_timeout(1500)
        n = await pg.evaluate("S.frames.length"); print('frames made', n > 15, n)
        print('one undo step', await pg.evaluate("undoStack.length") == u0 + 1)
        q = await pg.evaluate(f"S.frames.map(f=>f.pp['{ids['head']}']||{{}})")
        print('head thrown back (squashed)', abs(q[5].get('sy', 1) - 0.82) < 0.02, q[5].get('sy'))
        arm = await pg.evaluate(f"S.frames.map(f=>(f.pp['{ids['armL']}']||{{}}).dy||0)")
        print('shoulders up', arm[6] < -1, arm[6])
        tr = await pg.evaluate(f"S.frames.slice(6,14).map(f=>(f.pp['{ids['torso']}']||{{}}).r||0)")
        print('body trembles', max(tr) - min(tr) > 3, [round(x, 1) for x in tr])
        ab = [await pg.evaluate(f"ppCurAbs(S.frames[{i}], ppSelChar())") for i in (7, 8)]
        print('feet stay planted', all(abs(x['shinL'] - a0['shinL']) < 1 and abs(x['legR'] - a0['legR']) < 1 for x in ab))
        sh = await pg.evaluate("S.frames.map(f=>f.shake||0)"); print('camera shakes', max(sh) >= 14 and sh[-1] == 0, sh)
        sfx = await pg.evaluate("(S.audio&&S.audio.sfx||[]).map(s=>[S.frames.findIndex(f=>f.id===s.frameId),s.kind])")
        print('roar sfx', sfx == [[4, 'roar']] or (len(sfx) == 1 and sfx[0][1] == 'roar'), sfx)
        print('back to start pose', abs(await pg.evaluate(f"ppCurAbs(S.frames[{n-1}], ppSelChar()).armL") - a0['armL']) < 2)
        await pg.evaluate("S.cur=6; updateFrameUI(); requestRender()"); await pg.wait_for_timeout(300); await pg.screenshot(path='het_gian.png')
        await pg.evaluate("sfxBuffer('roar').then(b=>window._rl=b.length)"); await pg.wait_for_timeout(1500)
        print('roar renders', (await pg.evaluate("window._rl||0")) > 44100)
        await pg.evaluate("undo()"); await pg.wait_for_timeout(500)
        print('undo removes frames + sound', await pg.evaluate("S.frames.length") == 1 and await pg.evaluate("(S.audio&&S.audio.sfx||[]).length") == 0)
        await pg.evaluate("redo()"); await pg.wait_for_timeout(500)
        print('redo', await pg.evaluate("S.frames.length") == n and await pg.evaluate("S.audio.sfx.length") == 1)
        await pg.evaluate("undo()"); await pg.wait_for_timeout(500)
        await pg.click('#gestFx'); await pg.click('#ppGests >> text=Giơ nắm đấm gào'); await pg.wait_for_timeout(1500)
        n2 = await pg.evaluate("S.frames.length"); ab = await pg.evaluate("ppCurAbs(S.frames[6], ppSelChar())")
        print('rage: fists up', n2 > 15 and (ab['foreR'] < -30 or ab['foreR'] > 270), ab['foreR'], ab['foreL'])
        print('fx off: no shake, no sound', not any(await pg.evaluate("S.frames.map(f=>f.shake||0)")) and await pg.evaluate("(S.audio&&S.audio.sfx||[]).length") == 0)
        await pg.evaluate("S.cur=7; updateFrameUI(); requestRender()"); await pg.wait_for_timeout(300); await pg.screenshot(path='het_gian_rage.png')
        print('ERR', errs); await b.close()
asyncio.run(main()); srv.kill()
